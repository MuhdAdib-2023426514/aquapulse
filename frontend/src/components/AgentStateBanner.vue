<script setup lang="ts">
import { computed } from 'vue'
import { useAquaStore } from '../store'

const store = useAquaStore()

const state = computed(() => {
  if (store.mode === 'scenario') return store.scenarioData?.system1_trace?.overall_state || null
  return store.currentFrame?.system1_trace?.overall_state || null
})

const title = computed(() => {
  if (store.mode === 'scenario') return 'Scripted scenario'
  if (store.capabilities === null) return 'AI status unavailable'
  if (!store.capabilities.yolo26_pose_available) return 'Pose model unavailable'
  return 'Experimental video review'
})

const description = computed(() => {
  if (store.mode === 'scenario') return 'Displayed states and events are generated by a scripted example.'
  if (store.capabilities === null) return 'The local API did not report model status.'
  if (!store.capabilities.yolo26_pose_available) {
    return 'Pose weights are missing. This clip cannot produce person tracking or movement cues.'
  }
  return 'Pose and movement cues are unvalidated. Review the source footage; do not treat cues as a confirmed event.'
})
</script>

<template>
  <aside class="agent-banner">
    <div class="banner-left">
      <span class="state-chip">{{ title }}</span>
      <p class="state-desc">{{ description }}</p>
    </div>
    <div class="banner-right" v-if="store.mode === 'scenario' && state">
      <span class="kpi-label">Scripted state</span>
      <strong class="kpi-val">{{ String(state).replace(/_/g, ' ') }}</strong>
    </div>
    <div class="banner-right" v-else-if="store.mode === 'video' && store.activeJob">
      <span class="kpi-label">Clip position</span>
      <strong class="kpi-val">{{ store.playheadSec.toFixed(1) }}s / {{ store.activeJob.duration_sec.toFixed(1) }}s</strong>
    </div>
  </aside>
</template>

